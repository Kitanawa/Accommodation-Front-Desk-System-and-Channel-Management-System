ALTER TABLE payments ADD COLUMN kind varchar(10) NOT NULL DEFAULT 'PAYMENT' CHECK (kind IN ('PAYMENT','DEPOSIT'));
ALTER TABLE payments ADD COLUMN idempotency_key varchar(80);
ALTER TABLE payments ADD COLUMN received_by uuid REFERENCES users(user_id);
