-- ---- charges: recorded prices cannot be changed or deleted; a mistake is voided (S097)
ALTER TABLE charges ADD COLUMN stay_date   date;
ALTER TABLE charges ADD COLUMN voided_at   timestamptz;
ALTER TABLE charges ADD COLUMN voided_by   uuid REFERENCES users(user_id);
ALTER TABLE charges ADD COLUMN void_reason varchar(200);
UPDATE charges SET stay_date = substring(description from 'Room night ([0-9]{4}-[0-9]{2}-[0-9]{2})')::date WHERE charge_type = 'ROOM';
CREATE INDEX charges_stay_date ON charges (stay_date) WHERE charge_type = 'ROOM';

CREATE FUNCTION charges_guard() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'A recorded charge cannot be deleted. Void it instead.';
  END IF;
  IF NEW.charge_id IS DISTINCT FROM OLD.charge_id OR NEW.folio_id IS DISTINCT FROM OLD.folio_id
     OR NEW.charge_type IS DISTINCT FROM OLD.charge_type OR NEW.description IS DISTINCT FROM OLD.description
     OR NEW.quantity IS DISTINCT FROM OLD.quantity OR NEW.unit_price IS DISTINCT FROM OLD.unit_price
     OR NEW.amount IS DISTINCT FROM OLD.amount OR NEW.charged_at IS DISTINCT FROM OLD.charged_at
     OR NEW.add_on_id IS DISTINCT FROM OLD.add_on_id OR NEW.stay_date IS DISTINCT FROM OLD.stay_date THEN
    RAISE EXCEPTION 'A recorded charge cannot be changed. Void it and post a new one.';
  END IF;
  IF OLD.voided_at IS NOT NULL AND (NEW.voided_at IS DISTINCT FROM OLD.voided_at OR NEW.voided_by IS DISTINCT FROM OLD.voided_by
     OR NEW.void_reason IS DISTINCT FROM OLD.void_reason) THEN
    RAISE EXCEPTION 'A voided charge cannot be changed.';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;
CREATE TRIGGER charges_guard BEFORE UPDATE OR DELETE ON charges FOR EACH ROW EXECUTE FUNCTION charges_guard();

-- ---- folios: recorded tax rate and an invoice number (S097, S099, S102)
ALTER TABLE folios ADD COLUMN tax_name varchar(30);
ALTER TABLE folios ADD COLUMN tax_rate_pct numeric(5,2) NOT NULL DEFAULT 0 CHECK (tax_rate_pct >= 0 AND tax_rate_pct <= 100);
ALTER TABLE folios ADD COLUMN invoice_no bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE UNIQUE INDEX folios_invoice_no ON folios (invoice_no);

-- ---- discounts (S099): the amount is recorded when the discount is given
CREATE TABLE folio_discounts (
  discount_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  folio_id    uuid NOT NULL REFERENCES folios,
  kind        varchar(10) NOT NULL CHECK (kind IN ('PERCENT','FIXED')),
  value       numeric(12,2) NOT NULL CHECK (value > 0),
  amount      numeric(12,2) NOT NULL CHECK (amount > 0),
  reason      varchar(200) NOT NULL,
  applied_by  uuid REFERENCES users(user_id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  voided_at   timestamptz,
  voided_by   uuid REFERENCES users(user_id),
  void_reason varchar(200)
);
CREATE INDEX folio_discounts_folio ON folio_discounts (folio_id);

