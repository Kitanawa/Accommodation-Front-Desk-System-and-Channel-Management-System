-- ---- refunds (S101)
CREATE TABLE refunds (
  refund_id     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  payment_id    uuid NOT NULL REFERENCES payments,
  folio_id      uuid NOT NULL REFERENCES folios,
  amount        numeric(12,2) NOT NULL CHECK (amount > 0),
  reason        varchar(200) NOT NULL,
  status        varchar(10) NOT NULL DEFAULT 'REQUESTED' CHECK (status IN ('REQUESTED','COMPLETED','REJECTED')),
  requested_by  uuid REFERENCES users(user_id),
  requested_at  timestamptz NOT NULL DEFAULT now(),
  decided_by    uuid REFERENCES users(user_id),
  decided_at    timestamptz,
  decision_note varchar(200),
  refund_no     bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE UNIQUE INDEX refunds_refund_no ON refunds (refund_no);
CREATE INDEX refunds_payment ON refunds (payment_id);
CREATE INDEX refunds_folio ON refunds (folio_id);

-- ---- property policies (S105)
CREATE TABLE property_settings (
  property_id           uuid PRIMARY KEY REFERENCES properties,
  tax_name              varchar(30),
  tax_rate_pct          numeric(5,2) NOT NULL DEFAULT 0 CHECK (tax_rate_pct >= 0 AND tax_rate_pct <= 100),
  check_in_time         time NOT NULL DEFAULT '14:00',
  check_out_time        time NOT NULL DEFAULT '12:00',
  cancellation_policy   varchar(1000),
  hold_minutes          smallint NOT NULL DEFAULT 15 CHECK (hold_minutes BETWEEN 1 AND 60),
  post_stay_room_status varchar(10) NOT NULL DEFAULT 'CLEANING' CHECK (post_stay_room_status IN ('CLEANING','AVAILABLE')),
  updated_at            timestamptz NOT NULL DEFAULT now()
);
INSERT INTO property_settings (property_id) SELECT property_id FROM properties;

-- ---- housekeeping (S103)
CREATE TABLE housekeeping_tasks (
  task_id        uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  room_id        uuid NOT NULL REFERENCES rooms,
  reservation_id uuid REFERENCES reservations,
  task_type      varchar(15) NOT NULL CHECK (task_type IN ('CHECKOUT_CLEAN','DAILY_CLEAN','INSPECTION')),
  status         varchar(12) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','IN_PROGRESS','DONE','CANCELLED')),
  assigned_to    uuid REFERENCES users(user_id),
  notes          varchar(300),
  created_by     uuid REFERENCES users(user_id),
  created_at     timestamptz NOT NULL DEFAULT now(),
  started_at     timestamptz,
  done_at        timestamptz
);
CREATE INDEX housekeeping_status ON housekeeping_tasks (status);
CREATE INDEX housekeeping_room ON housekeeping_tasks (room_id);

-- ---- maintenance (S104)
CREATE TABLE maintenance_reports (
  report_id       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  room_id         uuid NOT NULL REFERENCES rooms,
  issue           varchar(300) NOT NULL,
  severity        varchar(6) NOT NULL DEFAULT 'MEDIUM' CHECK (severity IN ('LOW','MEDIUM','HIGH')),
  blocks_room     boolean NOT NULL DEFAULT false,
  status          varchar(10) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','RESOLVED','CANCELLED')),
  reported_by     uuid REFERENCES users(user_id),
  reported_at     timestamptz NOT NULL DEFAULT now(),
  resolved_by     uuid REFERENCES users(user_id),
  resolved_at     timestamptz,
  resolution_note varchar(300)
);
CREATE INDEX maintenance_room_open ON maintenance_reports (room_id) WHERE status = 'OPEN';

-- ---- notifications (S105)
CREATE TABLE notification_preferences (
  user_id    uuid NOT NULL REFERENCES users(user_id),
  event_code varchar(30) NOT NULL,
  channel    varchar(10) NOT NULL CHECK (channel IN ('IN_APP','EMAIL')),
  enabled    boolean NOT NULL,
  PRIMARY KEY (user_id, event_code, channel)
);
CREATE TABLE notification_logs (
  log_id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  property_id       uuid NOT NULL REFERENCES properties,
  event_code        varchar(30) NOT NULL,
  channel           varchar(10) NOT NULL CHECK (channel IN ('IN_APP','EMAIL')),
  recipient_user_id uuid REFERENCES users(user_id),
  subject           varchar(200) NOT NULL,
  payload           jsonb,
  status            varchar(10) NOT NULL CHECK (status IN ('QUEUED','DELIVERED','FAILED')),
  error             varchar(300),
  created_at        timestamptz NOT NULL DEFAULT now(),
  delivered_at      timestamptz,
  read_at           timestamptz
);
CREATE INDEX notification_logs_recipient ON notification_logs (recipient_user_id, created_at DESC);
CREATE INDEX notification_logs_property ON notification_logs (property_id, created_at DESC);
